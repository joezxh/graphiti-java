/**
 * 替换中文值为对应语言翻译
 */
function translateBlock(block, lang, namespace) {
  const transMap = translations[lang][namespace]
  if (!transMap) return block
  
  let result = block
  Object.entries(transMap).forEach(([zh, trans]) => {
    const escapedZh = zh.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
    const regex = new RegExp(`'${escapedZh}'`, 'g')
    result = result.replace(regex, `'${trans}'`)
  })
  
  return result
}

/**
 * 添加到目标文件
 */
function addToTargetFile(targetFile, lang) {
  const filePath = path.join(BASE_DIR, targetFile)
  let content = fs.readFileSync(filePath, 'utf8')
  
  // 检查是否已经存在
  if (content.includes('  propertyEditor:')) {
    console.log(`⏭️  ${targetFile} 已存在propertyEditor,跳过`)
    return
  }
  
  // 翻译命名空间
  const translatedPropertyEditor = translateBlock(propertyEditorBlock, lang, 'propertyEditor')
  const translatedClassEditor = translateBlock(classEditorBlock, lang, 'classEditor')
  
  // 在graphIde之前插入
  const insertPos = content.indexOf('  graphIde:')
  if (insertPos === -1) {
    console.error(`❌ ${targetFile} 中未找到graphIde命名空间`)
    return
  }
  
  const insertion = translatedPropertyEditor + '\n' + translatedClassEditor + '\n'
  content = content.slice(0, insertPos) + insertion + content.slice(insertPos)
  
  fs.writeFileSync(filePath, content, 'utf8')
  console.log(`✅ ${targetFile} 已添加propertyEditor和classEditor`)
}

